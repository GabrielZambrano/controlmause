  0x37: 0x43, 0x38: 0x3a, 0x39: 0x31, 0x3a: 0x39,             // * Alt Espacio BloqMayus
  0x3b: 0x7a, 0x3c: 0x78, 0x3d: 0x63, 0x3e: 0x76, 0x3f: 0x60,
  0x40: 0x61, 0x41: 0x62, 0x42: 0x64, 0x43: 0x65, 0x44: 0x6d, // F1..F10
  0x45: 0x47,                                                 // BloqNum -> Clear
  0x47: 0x59, 0x48: 0x5b, 0x49: 0x5c, 0x4a: 0x4e,
