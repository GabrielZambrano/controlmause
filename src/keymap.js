// Traduce teclas de Windows a codigos de tecla de Mac.
// Usamos el codigo de escaneo (posicion fisica de la tecla), no la letra, para que
// la distribucion del teclado (por ejemplo, Espanol) la decida la Mac.

// Codigos de escaneo de Windows (set 1) sin prefijo E0.
